import "server-only";
import fs from "node:fs/promises";
import path from "node:path";

/**
 * Replay object storage.
 *  - S3-compatible (Cloudflare R2): set S3_ENDPOINT, S3_BUCKET, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY
 *  - otherwise the local filesystem under STORAGE_DIR (default .data/replays; a Railway volume in prod)
 * Objects are never public; reads go through our own route handlers.
 */
export interface Stored {
  body: ReadableStream<Uint8Array>;
  size: number;
}

const s3 = () => {
  const { S3_ENDPOINT, S3_BUCKET, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY } = process.env;
  if (!S3_ENDPOINT || !S3_BUCKET || !S3_ACCESS_KEY_ID || !S3_SECRET_ACCESS_KEY) return null;
  return { endpoint: S3_ENDPOINT.replace(/\/$/, ""), bucket: S3_BUCKET, key: S3_ACCESS_KEY_ID, secret: S3_SECRET_ACCESS_KEY };
};

const root = () => path.resolve(process.env.STORAGE_DIR ?? ".data/replays");

/** Keys are generated by us (hash based); still refuse anything that could escape the root. */
function safeKey(key: string): string {
  if (!/^[a-z0-9][a-z0-9/_.-]*$/i.test(key) || key.includes("..")) throw new Error("bad storage key");
  return key;
}

async function client(cfg: NonNullable<ReturnType<typeof s3>>) {
  const { AwsClient } = await import("aws4fetch");
  const aws = new AwsClient({ accessKeyId: cfg.key, secretAccessKey: cfg.secret, service: "s3", region: "auto" });
  return { aws, url: (key: string) => `${cfg.endpoint}/${cfg.bucket}/${safeKey(key)}` };
}

export async function putObject(key: string, data: Uint8Array): Promise<void> {
  const cfg = s3();
  if (cfg) {
    const c = await client(cfg);
    const res = await c.aws.fetch(c.url(key), { method: "PUT", body: data as BodyInit, headers: { "content-type": "application/octet-stream" } });
    if (!res.ok) throw new Error(`storage put failed: ${res.status}`);
    return;
  }
  const file = path.join(root(), safeKey(key));
  await fs.mkdir(path.dirname(file), { recursive: true });
  await fs.writeFile(file, data);
}

export async function getObject(key: string): Promise<Stored | null> {
  const cfg = s3();
  if (cfg) {
    const c = await client(cfg);
    const res = await c.aws.fetch(c.url(key));
    if (res.status === 404 || !res.body) return null;
    if (!res.ok) throw new Error(`storage get failed: ${res.status}`);
    return { body: res.body, size: Number(res.headers.get("content-length") ?? 0) };
  }
  try {
    const buf = await fs.readFile(path.join(root(), safeKey(key)));
    return { body: new Response(buf).body!, size: buf.byteLength };
  } catch {
    return null;
  }
}

export async function deleteObject(key: string): Promise<void> {
  const cfg = s3();
  if (cfg) {
    const c = await client(cfg);
    const res = await c.aws.fetch(c.url(key), { method: "DELETE" });
    if (!res.ok && res.status !== 404) throw new Error(`storage delete failed: ${res.status}`);   // a missing object is already gone
    return;
  }
  await fs.rm(path.join(root(), safeKey(key)), { force: true });
}

/** Names of the stored objects whose key starts with `prefix` (used by the deletion ledger and its expiry). */
export async function listObjects(prefix: string): Promise<string[]> {
  safeKey(prefix.replace(/\/$/, "") || "x");
  const cfg = s3();
  if (cfg) {
    const c = await client(cfg);
    const out: string[] = [];
    let token = "";
    for (let page = 0; page < 100; page++) {
      const url = `${cfg.endpoint}/${cfg.bucket}?list-type=2&prefix=${encodeURIComponent(prefix)}${token ? `&continuation-token=${encodeURIComponent(token)}` : ""}`;
      const res = await c.aws.fetch(url);
      if (!res.ok) throw new Error(`storage list failed: ${res.status}`);
      const xml = await res.text();
      for (const m of xml.matchAll(/<Key>([^<]*)<\/Key>/g)) out.push(m[1].replace(/&amp;/g, "&"));
      token = /<IsTruncated>true<\/IsTruncated>/.test(xml) ? (xml.match(/<NextContinuationToken>([^<]*)<\/NextContinuationToken>/)?.[1] ?? "") : "";
      if (!token) break;
    }
    return out;
  }
  const dir = path.join(root(), prefix);
  const out: string[] = [];
  const walk = async (d: string, rel: string): Promise<void> => {
    let entries;
    try {
      entries = await fs.readdir(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      if (e.isDirectory()) await walk(path.join(d, e.name), `${rel}${e.name}/`);
      else out.push(`${rel}${e.name}`);
    }
  };
  await walk(dir, prefix);
  return out;
}
